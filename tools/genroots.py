#!/usr/bin/env python3
"""genroots.py - build kernel/net/roots.c, the built-in TLS root certificates.

Reads the public root certificates of the Mozilla CA program as shipped by the
Debian/Ubuntu ca-certificates package (/usr/share/ca-certificates/mozilla/*.crt;
only that directory, never locally added CAs) and writes them as DER arrays.
Roots that have already expired are left out.

    python3 tools/genroots.py [DIR] > kernel/net/roots.c
"""
import datetime
import glob
import os
import sys

from cryptography import x509
from cryptography.x509.oid import NameOID

src = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/ca-certificates/mozilla"
now = datetime.datetime.now(datetime.timezone.utc)
certs = []
for path in sorted(glob.glob(os.path.join(src, "*.crt"))):
    with open(path, "rb") as f:
        c = x509.load_pem_x509_certificate(f.read())
    if c.not_valid_after_utc < now:
        continue
    names = c.subject.get_attributes_for_oid(NameOID.COMMON_NAME) or \
            c.subject.get_attributes_for_oid(NameOID.ORGANIZATIONAL_UNIT_NAME) or \
            c.subject.get_attributes_for_oid(NameOID.ORGANIZATION_NAME)
    name = names[0].value if names else os.path.basename(path)
    certs.append((name, c.public_bytes(encoding=__import__("cryptography.hazmat.primitives.serialization",
                                                           fromlist=["Encoding"]).Encoding.DER)))

out = sys.stdout
out.write("/*\n * roots.c - built-in TLS root certificates (%d), generated by tools/genroots.py from the\n"
          " * Mozilla CA program list (ca-certificates). Do not edit by hand.\n */\n" % len(certs))
out.write('#include "net_internal.h"\n\n')
for i, (name, der) in enumerate(certs):
    out.write("/* %s */\nstatic const uint8_t root%d[%d] = {\n" % (name.replace("*/", "* /"), i, len(der)))
    for j in range(0, len(der), 24):
        out.write("    " + ",".join("0x%02x" % b for b in der[j:j + 24]) + ",\n")
    out.write("};\n")
out.write("\nconst tls_root_t tls_roots[] = {\n")
for i, (name, der) in enumerate(certs):
    out.write("    { root%d, %d },\n" % (i, len(der)))
out.write("};\nconst int tls_root_count = %d;\n" % len(certs))
