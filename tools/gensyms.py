#!/usr/bin/env python3
"""gensyms.py - turn `nm -n --defined-only kernel.elf` output (stdin) into a C symbol table.

The table lives in the .ksyms section, which the linker script places after .rodata, so
adding it does not move any code: addresses from the first link stay valid in the final one.
The panic screen uses it to print stack traces as function+offset.
"""
import sys

syms = []
for line in sys.stdin:
    parts = line.split()
    if len(parts) != 3:
        continue
    addr, kind, name = parts
    if kind not in "Tt" or name.startswith(".") or name.startswith("$"):
        continue
    syms.append((int(addr, 16), name))
syms.sort()

out = sys.stdout
out.write("/* Generated by tools/gensyms.py - do not edit. */\n#include <stdint.h>\n")
out.write("typedef struct { uint32_t addr; uint32_t name; } ksym_t;\n")
out.write('#define KS __attribute__((section(".ksyms"), used))\n')
out.write("KS const uint32_t ksyms_count = %d;\n" % len(syms))
names = bytearray()
entries = []
for addr, name in syms:
    entries.append((addr, len(names)))
    names += name.encode() + b"\0"
out.write("KS const ksym_t ksyms_table[%d] = {\n" % max(1, len(entries)))
for addr, off in entries:
    out.write("  {0x%08x, %d},\n" % (addr, off))
if not entries:
    out.write("  {0, 0}\n")
out.write("};\n")
out.write("KS const char ksyms_names[%d] = {\n" % max(1, len(names)))
for i in range(0, len(names), 32):
    out.write("  " + ",".join(str(b) for b in names[i:i + 32]) + ",\n")
if not names:
    out.write("  0\n")
out.write("};\n")
