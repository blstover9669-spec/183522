#!/usr/bin/env python3
"""
genwebfont.py - generate the Web Browser's page fonts (apps/web_fontdata.c).

The browser lays out web pages in many font sizes and in regular, bold,
italic, bold italic and monospace styles, so it carries its own font set:
Liberation Sans (Arial-compatible metrics, what most pages ask for) and
Liberation Mono (pre / code), rendered with PIL like tools/genfont.py.

  * small sizes (9-24 px) are rendered hinted, one table per size
  * one 48 px "master" per proportional style; the browser scales it at
    runtime for every bigger size (monospace text stops at 24 px)

Each font is stored as base64(zlib(glyph table + 8-bit coverage bitmaps))
and unpacked by apps/web_font.c the first time a page uses it.

Character set: Windows-1252 (what web text is converted to), with arrows
and a check mark in the five unused 0x80-0x9F slots:
  0x81 right arrow, 0x8D left arrow, 0x8F up arrow, 0x90 down arrow, 0x9D check mark

Usage:  python3 tools/genwebfont.py [output.c]
"""
import sys, zlib, base64
from PIL import Image, ImageFont

LIB = "/usr/share/fonts/truetype/liberation/"
DEJAVU = "/usr/share/fonts/truetype/dejavu/"

CP80 = [0x20AC, 0x2192, 0x201A, 0x0192, 0x201E, 0x2026, 0x2020, 0x2021,
        0x02C6, 0x2030, 0x0160, 0x2039, 0x0152, 0x2190, 0x017D, 0x2191,
        0x2193, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2013, 0x2014,
        0x02DC, 0x2122, 0x0161, 0x203A, 0x0153, 0x2713, 0x017E, 0x0178]

def codepoint(i):
    if 0x80 <= i <= 0x9F:
        return CP80[i - 0x80]
    return i

STYLES = [
    # id, name, files (fallback chain)
    (0, "regular",    [LIB + "LiberationSans-Regular.ttf", DEJAVU + "DejaVuSans.ttf"]),
    (1, "bold",       [LIB + "LiberationSans-Bold.ttf", DEJAVU + "DejaVuSans-Bold.ttf"]),
    (2, "italic",     [LIB + "LiberationSans-Italic.ttf", DEJAVU + "DejaVuSans.ttf"]),
    (3, "bolditalic", [LIB + "LiberationSans-BoldItalic.ttf", DEJAVU + "DejaVuSans-Bold.ttf"]),
    (4, "mono",       [LIB + "LiberationMono-Regular.ttf", DEJAVU + "DejaVuSansMono.ttf", DEJAVU + "DejaVuSans.ttf"]),
    (5, "monobold",   [LIB + "LiberationMono-Bold.ttf", DEJAVU + "DejaVuSansMono-Bold.ttf", DEJAVU + "DejaVuSans-Bold.ttf"]),
]
SMALL = [9, 10, 11, 12, 13, 14, 15, 16, 18, 20, 22, 24]
MASTER = 48
FIRST, LAST = 0x20, 0xFF

def gamma(a, g=0.85):
    return int(round(255.0 * ((a / 255.0) ** g)))

_sigs = {}
def notdef_sig(font):
    k = id(font)
    if k not in _sigs:
        m, _ = font.getmask2(chr(0x10FFFD), mode="L", anchor="ls")
        _sigs[k] = (m.size, bytes(m))
    return _sigs[k]

def glyph(fonts, ch, ascent, q16):
    for font in fonts:
        mask, off = font.getmask2(ch, mode="L", anchor="ls")
        if (mask.size, bytes(mask)) == notdef_sig(font) and ch != " ":
            continue
        w, h = mask.size
        data = bytes(gamma(b) for b in bytes(mask))
        if q16:   # 16 levels compress much better and look the same at these sizes
            data = bytes(min(255, ((b + 8) // 17) * 17) for b in data)
        adv = int(round(font.getlength(ch)))
        xoff, yoff = off[0], off[1] + ascent
        if w and h:
            img = Image.frombytes("L", (w, h), data)
            bb = img.getbbox()
            if bb:
                img = img.crop(bb)
                xoff += bb[0]; yoff += bb[1]
                w, h = img.size
                data = img.tobytes()
            else:
                w = h = 0; data = b""
        else:
            w = h = 0; data = b""
        return adv, xoff, yoff, w, h, data
    return None

def make(files, px, q16):
    fonts = [ImageFont.truetype(p, px) for p in files]
    asc, desc = fonts[0].getmetrics()
    height = asc + desc
    table = bytearray()
    blob = bytearray()
    mono = 0
    for i in range(FIRST, LAST + 1):
        g = glyph(fonts, chr(codepoint(i)), asc, q16)
        if g is None:
            g = glyph(fonts, "?", asc, q16)
        adv, xoff, yoff, w, h, data = g
        assert 0 <= adv < 256 and -128 <= xoff < 128 and -128 <= yoff < 128 and w < 256 and h < 256
        table += bytes([adv, xoff + 128, yoff + 128, w, h])
        blob += data
    return height, asc, bytes(table + blob)

def emit(out):
    w = out.write
    w("/* Generated by tools/genwebfont.py - DO NOT EDIT. */\n")
    w("/* Glyphs rendered from Liberation Sans / Mono (SIL OFL 1.1) and DejaVu fonts. */\n")
    w('#include "web.h"\n\n')
    entries = []
    total = 0
    for sid, sname, files in STYLES:
        for px in SMALL + ([] if sname.startswith("mono") else [MASTER]):
            height, asc, raw = make(files, px, True)
            comp = zlib.compress(raw, 9)
            b64 = base64.b64encode(comp).decode()
            name = "wf_%s_%d" % (sname, px)
            w("static const char %s[] =\n" % name)
            for k in range(0, len(b64), 100):
                w('  "%s"\n' % b64[k:k + 100])
            w(";\n")
            entries.append((sid, px, height, asc, len(comp), len(raw), name))
            total += len(comp)
            sys.stderr.write("%-11s %2dpx line=%d raw=%d z=%d\n" % (sname, px, height, len(raw), len(comp)))
    w("\nconst web_fontpack_t web_fontpacks[] = {\n")
    for e in entries:
        w("  { %d, %d, %d, %d, %d, %d, %s },\n" % e)
    w("};\nconst int web_fontpack_count = %d;\n" % len(entries))
    sys.stderr.write("total compressed: %d bytes\n" % total)

if __name__ == "__main__":
    path = sys.argv[1] if len(sys.argv) > 1 else "apps/web_fontdata.c"
    with open(path, "w") as fh:
        emit(fh)
